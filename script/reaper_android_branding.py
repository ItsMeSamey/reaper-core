# Do not rewrite literal URLs even if a translator capitalized their host.
_URI = re.compile(r"([A-Za-z][A-Za-z0-9+.-]*:[^\s<>\"']+|www\.[^\s<>\"']+)")


def Rebrand(message_id, text, lang='en'):
    # This localized location label names a third-party store, not this browser.
    is_store_location = message_id == 'IDS_EXTENSIONS_INSTALL_LOCATION_UNKNOWN'
    if not is_store_location and message_id not in PRODUCT_MESSAGE_IDS:
        return text
    brand = 'Chrome' if is_store_location else 'Reaper'
    if is_store_location and lang.split('-')[0] == 'en':
        if text.strip() == 'Not from Web Store.':
            text = text.replace('Web Store', 'Chrome Web Store')
    # Preserve genuine localized Chrome spellings in the service label. Only
    # the erroneous Brave product token is replaced there.
    tokens = ('Brave',) if is_store_location else ('Brave',) + _LOCALIZED_BRANDS.get(
        lang, _LOCALIZED_BRANDS.get(lang.split('-')[0], ()))
    parts = _URI.split(text)
    for index in range(0, len(parts), 2):
        for token in tokens:
            if token == 'hrome':
                parts[index] = re.sub(r'(?<![A-Za-z])hrome', brand, parts[index])
            else:
                parts[index] = parts[index].replace(token, brand)
    return ''.join(parts)
